import { describe, it, expect, beforeAll } from 'vitest';
import { createClient, SupabaseClient } from '@supabase/supabase-js';
import fs from 'fs';
import path from 'path';
import {
  mapProfile,
  mapRentals,
  mapFlips,
  mapOpportunities,
  mapFundingSources,
  extractAndMapBOQItems,
  mapTasks,
  mapSuppliers,
} from '../migrateToCloud';
import {
  INITIAL_INVESTOR_PROFILE,
  INITIAL_RENTALS,
  INITIAL_FLIPS,
  INITIAL_OPPORTUNITIES,
  INITIAL_FUNDING_SOURCES,
} from '@/lib/store/initialData';

/**
 * Remote Database Schema Parity Integration Test (DBSYNC-PARITY)
 *
 * Queries Supabase's live information_schema.columns via the get_schema_columns RPC / view
 * to assert that every key generated by local-to-cloud mappers (mapProfile, mapRentals, mapFlips, etc.)
 * is an existing, recognized column in the remote PostgreSQL tables.
 *
 * Prevents PostgREST schema cache misses such as:
 * "Could not find the 'marginal_tax_rate_percent' column of 'profiles' in the schema cache"
 */

function loadEnvCredentials() {
  let url = process.env.NEXT_PUBLIC_SUPABASE_URL;
  let anonKey = process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY;

  if (!url || !anonKey) {
    const envPath = path.resolve(process.cwd(), '.env.local');
    if (fs.existsSync(envPath)) {
      const content = fs.readFileSync(envPath, 'utf-8');
      for (const line of content.split('\n')) {
        const trimmed = line.trim();
        if (trimmed.startsWith('NEXT_PUBLIC_SUPABASE_URL=')) {
          url = trimmed.split('=')[1]?.trim();
        }
        if (trimmed.startsWith('NEXT_PUBLIC_SUPABASE_ANON_KEY=')) {
          anonKey = trimmed.split('=')[1]?.trim();
        }
      }
    }
  }

  return { url, anonKey };
}

describe('Remote Supabase Schema Parity Integration Test', () => {
  let client: SupabaseClient;
  let remoteSchemaMap: Map<string, Set<string>>;

  beforeAll(async () => {
    const { url, anonKey } = loadEnvCredentials();
    expect(url, 'NEXT_PUBLIC_SUPABASE_URL must be defined for integration testing').toBeDefined();
    expect(anonKey, 'NEXT_PUBLIC_SUPABASE_ANON_KEY must be defined for integration testing').toBeDefined();

    client = createClient(url!, anonKey!);

    // Query information_schema.columns via RPC
    const { data, error } = await client.rpc('get_schema_columns');
    expect(error, `Failed to query information_schema.columns: ${error?.message}`).toBeNull();
    expect(Array.isArray(data), 'Schema columns data must be an array').toBe(true);

    remoteSchemaMap = new Map();
    for (const row of data as { table_name: string; column_name: string }[]) {
      if (!remoteSchemaMap.has(row.table_name)) {
        remoteSchemaMap.set(row.table_name, new Set());
      }
      remoteSchemaMap.get(row.table_name)!.add(row.column_name);
    }
  }, 15000);

  it('asserts every key generated by mapProfile exists in remote profiles table', () => {
    const remoteProfilesColumns = remoteSchemaMap.get('profiles');
    expect(remoteProfilesColumns, 'Remote profiles table must exist in information_schema').toBeDefined();

    const mappedProfile = mapProfile(
      INITIAL_INVESTOR_PROFILE,
      'test-parity-user-id',
      'test@example.co.za',
      {
        liquidCapitalReserve: 100000,
        rentalForecastView: 'wealth-only',
        aiSettings: { provider: 'anthropic', model: 'claude-sonnet-5' },
        analyzerDraft: { openMarketValue: 1000000 },
      }
    );

    const generatedKeys = Object.keys(mappedProfile);
    const missingKeys = generatedKeys.filter((key) => !remoteProfilesColumns!.has(key));

    expect(
      missingKeys,
      `Found keys generated by mapProfile that DO NOT EXIST in remote profiles table: ${missingKeys.join(', ')}`
    ).toEqual([]);

    // Specific regression guard for the reported issue
    expect(remoteProfilesColumns!.has('marginal_tax_rate_percent')).toBe(true);
    expect(remoteProfilesColumns!.has('min_net_yield_percent')).toBe(true);
    expect(remoteProfilesColumns!.has('min_monthly_cashflow_zar')).toBe(true);
    expect(remoteProfilesColumns!.has('min_net_roi_percent')).toBe(true);
    expect(remoteProfilesColumns!.has('min_flip_roi_percent')).toBe(true);
    expect(remoteProfilesColumns!.has('max_day1_cash_zar')).toBe(true);
    expect(remoteProfilesColumns!.has('min_dscr')).toBe(true);
    expect(remoteProfilesColumns!.has('vat_exempt_agent')).toBe(true);
  });

  it('asserts every key generated by mapRentals exists in remote properties table', () => {
    const remotePropertiesColumns = remoteSchemaMap.get('properties');
    expect(remotePropertiesColumns, 'Remote properties table must exist in information_schema').toBeDefined();

    const mappedRentals = mapRentals(INITIAL_RENTALS, 'test-parity-user-id');
    expect(mappedRentals.length).toBeGreaterThan(0);

    const firstRental = mappedRentals[0];
    const generatedKeys = Object.keys(firstRental);
    const missingKeys = generatedKeys.filter((key) => !remotePropertiesColumns!.has(key));

    expect(
      missingKeys,
      `Found keys generated by mapRentals that DO NOT EXIST in remote properties table: ${missingKeys.join(', ')}`
    ).toEqual([]);
  });

  it('asserts every key generated by mapFlips exists in remote flips table', () => {
    const remoteFlipsColumns = remoteSchemaMap.get('flips');
    expect(remoteFlipsColumns, 'Remote flips table must exist in information_schema').toBeDefined();

    const mappedFlips = mapFlips(INITIAL_FLIPS, 'test-parity-user-id');
    expect(mappedFlips.length).toBeGreaterThan(0);

    const firstFlip = mappedFlips[0];
    const generatedKeys = Object.keys(firstFlip);
    const missingKeys = generatedKeys.filter((key) => !remoteFlipsColumns!.has(key));

    expect(
      missingKeys,
      `Found keys generated by mapFlips that DO NOT EXIST in remote flips table: ${missingKeys.join(', ')}`
    ).toEqual([]);
  });

  it('asserts all supporting mappers (opportunities, funding, boq, tasks, suppliers) match remote schema', () => {
    // 1. Opportunities -> opportunities table
    const remoteOppColumns = remoteSchemaMap.get('opportunities');
    expect(remoteOppColumns).toBeDefined();
    const mappedOpps = mapOpportunities(INITIAL_OPPORTUNITIES, 'test-parity-user-id');
    const missingOppKeys = Object.keys(mappedOpps[0] || {}).filter((k) => !remoteOppColumns!.has(k));
    expect(missingOppKeys, `Missing in opportunities: ${missingOppKeys.join(', ')}`).toEqual([]);

    // 2. Funding Sources -> funding_sources table
    const remoteFundingColumns = remoteSchemaMap.get('funding_sources');
    expect(remoteFundingColumns).toBeDefined();
    const mappedFunding = mapFundingSources(INITIAL_FUNDING_SOURCES, 'test-parity-user-id');
    const missingFundingKeys = Object.keys(mappedFunding[0] || {}).filter((k) => !remoteFundingColumns!.has(k));
    expect(missingFundingKeys, `Missing in funding_sources: ${missingFundingKeys.join(', ')}`).toEqual([]);

    // 3. BOQ Items -> boq_items table
    const remoteBoqColumns = remoteSchemaMap.get('boq_items');
    expect(remoteBoqColumns).toBeDefined();
    const mappedBoq = extractAndMapBOQItems(INITIAL_FLIPS, 'test-parity-user-id');
    const missingBoqKeys = Object.keys(mappedBoq[0] || {}).filter((k) => !remoteBoqColumns!.has(k));
    expect(missingBoqKeys, `Missing in boq_items: ${missingBoqKeys.join(', ')}`).toEqual([]);

    // 4. Tasks -> tasks table
    const remoteTaskColumns = remoteSchemaMap.get('tasks');
    expect(remoteTaskColumns).toBeDefined();
    const mappedTasks = mapTasks(
      [{ id: 't1', title: 'Task', status: 'Pending', priority: 'High' } as any],
      'test-parity-user-id'
    );
    const missingTaskKeys = Object.keys(mappedTasks[0] || {}).filter((k) => !remoteTaskColumns!.has(k));
    expect(missingTaskKeys, `Missing in tasks: ${missingTaskKeys.join(', ')}`).toEqual([]);

    // 5. Suppliers -> suppliers table
    const remoteSupplierColumns = remoteSchemaMap.get('suppliers');
    expect(remoteSupplierColumns).toBeDefined();
    const mappedSuppliers = mapSuppliers(
      [{ id: 's1', name: 'Supplier', category: 'Plumbing' } as any],
      'test-parity-user-id'
    );
    const missingSupplierKeys = Object.keys(mappedSuppliers[0] || {}).filter((k) => !remoteSupplierColumns!.has(k));
    expect(missingSupplierKeys, `Missing in suppliers: ${missingSupplierKeys.join(', ')}`).toEqual([]);
  });
});
